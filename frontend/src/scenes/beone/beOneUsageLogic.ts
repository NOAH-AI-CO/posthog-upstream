export const beOneUsageLogic = kea<beOneUsageLogicType>([
    path(['scenes', 'beone', 'beOneUsageLogic']),
    actions({
        setDraftFilters: (draftFilters: Partial<BeOneUsageFilters>) => ({ draftFilters }),
        applyFilters: true,
        setFilters: (filters: BeOneUsageFilters) => ({ filters }),
        resetFilters: true,
        reloadOverview: true,
        reloadFeed: true,
    }),
    reducers({
        draftFilters: [
            { ...DEFAULT_BEONE_FILTERS } as BeOneUsageFilters,
            {
                setDraftFilters: (state, { draftFilters }) => ({ ...state, ...draftFilters }),
                setFilters: (_, { filters }) => ({ ...filters }),
                resetFilters: () => ({ ...DEFAULT_BEONE_FILTERS }),
            },
        ],
        filters: [
            { ...DEFAULT_BEONE_FILTERS } as BeOneUsageFilters,
            {
                setFilters: (_, { filters }) => ({ ...filters }),
                resetFilters: () => ({ ...DEFAULT_BEONE_FILTERS }),
            },
        ],
        kpisLoaded: [
            false,
            {
                loadKpisSuccess: () => true,
                setFilters: () => false,
                resetFilters: () => false,
            },
        ],
        rankingLoaded: [
            false,
            {
                loadRankingSuccess: () => true,
                setFilters: () => false,
                resetFilters: () => false,
            },
        ],
        feedLoaded: [
            false,
            {
                loadFeedSuccess: () => true,
                setFilters: () => false,
                resetFilters: () => false,
            },
        ],
        usersLoaded: [
            false,
            {
                loadUsersSuccess: () => true,
                setFilters: () => false,
                resetFilters: () => false,
            },
        ],
        durationHistLoaded: [
            false,
            {
                loadDurationHistSuccess: () => true,
                setFilters: () => false,
                resetFilters: () => false,
            },
        ],
    }),
    loaders(({ values }) => ({
        kpis: [
            { todayActive: 0, periodActive: 0, todayEvents: 0, periodEvents: 0 } as BeOneKpis,
            {
                loadKpis: () =>
                    keepPreviousOnError(values.kpis, async () => {
                        const res = await api.queryHogQL(buildKpiQuery(values.filters), QUERY_TAGS, QUERY_OPTIONS)
                        return parseKpiRows(res.results)
                    }),
            },
        ],
        trend: [
            [] as BeOneTrendPoint[],
            {
                loadTrend: () =>
                    keepPreviousOnError(values.trend, async () => {
                        const res = await api.queryHogQL(buildTrendQuery(values.filters), QUERY_TAGS, QUERY_OPTIONS)
                        return parseTrendRows(res.results)
                    }),
            },
        ],
        ranking: [
            [] as BeOneRankingRow[],
            {
                loadRanking: () =>
                    keepPreviousOnError(values.ranking, async () => {
                        const res = await api.queryHogQL(buildRankingQuery(values.filters), QUERY_TAGS, QUERY_OPTIONS)
                        return parseRankingRows(res.results)
                    }),
            },
        ],
        feed: [
            [] as BeOneFeedRow[],
            {
                loadFeed: () =>
                    keepPreviousOnError(values.feed, async () => {
                        const res = await api.queryHogQL(buildFeedQuery(values.filters), QUERY_TAGS, QUERY_OPTIONS)
                        return parseFeedRows(res.results)
                    }),
            },
        ],
        users: [
            [] as BeOneUserRow[],
            {
                loadUsers: () =>
                    keepPreviousOnError(values.users, async () => {
                        const res = await api.queryHogQL(buildUserAggQuery(values.filters), QUERY_TAGS, QUERY_OPTIONS)
                        return parseUserAggRows(res.results)
                    }),
            },
        ],
        durationHist: [
            [] as BeOneDurationBucket[],
            {
                loadDurationHist: () =>
                    keepPreviousOnError(values.durationHist, async () => {
                        const res = await api.queryHogQL(
                            buildDurationHistQuery(values.filters),
                            QUERY_TAGS,
                            QUERY_OPTIONS
                        )
                        return parseDurationHistRows(res.results)
                    }),
            },
        ],
    })),
    selectors({
        trendGranularity: [
            (s) => [s.filters],
            (filters: BeOneUsageFilters): BeOneTrendGranularity => trendGranularityForRange(filters.range),
        ],
        hasAnyData: [
            (s) => [s.kpis, s.feed],
            (kpis: BeOneKpis, feed: BeOneFeedRow[]): boolean => kpis.periodEvents > 0 || feed.length > 0,
        ],
        // Skeletons only before the first response, so polls refresh in place instead of flickering
        kpisInitialLoading: [
            (s) => [s.kpisLoading, s.kpisLoaded],
            (kpisLoading: boolean, kpisLoaded: boolean): boolean => kpisLoading && !kpisLoaded,
        ],
        rankingInitialLoading: [
            (s) => [s.rankingLoading, s.rankingLoaded],
            (rankingLoading: boolean, rankingLoaded: boolean): boolean => rankingLoading && !rankingLoaded,
        ],
        feedInitialLoading: [
            (s) => [s.feedLoading, s.feedLoaded],
            (feedLoading: boolean, feedLoaded: boolean): boolean => feedLoading && !feedLoaded,
        ],
        usersInitialLoading: [
            (s) => [s.usersLoading, s.usersLoaded],
            (usersLoading: boolean, usersLoaded: boolean): boolean => usersLoading && !usersLoaded,
        ],
        durationHistInitialLoading: [
            (s) => [s.durationHistLoading, s.durationHistLoaded],
            (durationHistLoading: boolean, durationHistLoaded: boolean): boolean =>
                durationHistLoading && !durationHistLoaded,
        ],
    }),
    listeners(({ actions, values }) => ({
        reloadOverview: () => {
            actions.loadKpis()
            actions.loadTrend()
            actions.loadRanking()
            actions.loadUsers()
            actions.loadDurationHist()
        },
        reloadFeed: () => {
            actions.loadFeed()
        },
        applyFilters: () => {
            actions.setFilters({ ...values.draftFilters })
        },
        setFilters: () => {
            actions.reloadOverview()
            actions.reloadFeed()
        },
        resetFilters: () => {
            actions.reloadOverview()
            actions.reloadFeed()
        },
    })),
    afterMount(({ actions, cache }) => {
        actions.reloadOverview()
        actions.reloadFeed()

        cache.disposables.add(() => {
            const id = window.setInterval(() => {
                if (!document.hidden) {
                    actions.reloadOverview()
                }
            }, OVERVIEW_POLL_INTERVAL_MS)
            return () => clearInterval(id)
        }, 'overviewPoll')
        cache.disposables.add(() => {
            const id = window.setInterval(() => {
                if (!document.hidden) {
                    actions.reloadFeed()
                }
            }, FEED_POLL_INTERVAL_MS)
            return () => clearInterval(id)
        }, 'feedPoll')
        // Catch up immediately when the tab comes back instead of waiting up to a full interval
        cache.disposables.add(() => {
            const onVisibilityChange = (): void => {
                if (!document.hidden) {
                    actions.reloadOverview()
                    actions.reloadFeed()
                }
            }
            document.addEventListener('visibilitychange', onVisibilityChange)
            return () => document.removeEventListener('visibilitychange', onVisibilityChange)
        }, 'visibilityReload')
    }),
])
